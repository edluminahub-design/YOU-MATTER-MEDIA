"""
Builds the You Matter Media logo files from the brand portfolio PDF.

The logo is cream League Gothic on coral. Rather than retyping it, this traces
the glyphs embedded on the portfolio's cover — at their exact positions and
sizes — so the vector files match the supplied artwork exactly.

    pip install pymupdf fonttools
    python scripts/build_logo.py "path/to/You Matter Media Portfolio.pdf"

Writes:
    public/logo.svg, public/favicon.svg   square logo (as supplied)
    public/logo-512.png, public/apple-touch-icon.png, public/favicon-32.png
    src/data/logo.js                      horizontal lockup used by <Logo>
"""

import io
import os
import sys

import pymupdf
from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CORAL, CREAM = '#FF503A', '#E9E3DB'  # the logo's own colours, as in the PDF


def fmt(v):
    return ('%.2f' % v).rstrip('0').rstrip('.')


def main(pdf_path):
    doc = pymupdf.open(pdf_path)
    cover = doc[0]
    spans = [sp for sp in cover.get_texttrace() if 'LeagueGothic' in sp['font']]
    if not spans:
        raise SystemExit('No League Gothic text found on the cover.')

    xref = next(f[0] for f in cover.get_fonts(full=True) if 'LeagueGothic' in f[3])
    font = TTFont(io.BytesIO(doc.extract_font(xref)[3]))
    upem = font['head'].unitsPerEm
    glyphset = font.getGlyphSet()
    order = font.getGlyphOrder()

    def glyphs():
        for sp in spans:
            s = sp['size'] / upem
            for uni, gid, (ox, oy), _ in sp['chars']:
                if chr(uni) != ' ':
                    yield s, gid, ox, oy

    # Bounds of the whole lockup, in page space (y down).
    bp = BoundsPen(glyphset)
    for s, gid, ox, oy in glyphs():
        glyphset[order[gid]].draw(TransformPen(bp, (s, 0, 0, -s, ox, oy)))
    x0, y0, x1, y1 = bp.bounds
    tw, th = x1 - x0, y1 - y0

    def path(dx, dy, k, big):
        """Outlines of the name (big) or MEDIA, shifted by (dx, dy), scaled by k."""
        pen = SVGPathPen(glyphset, ntos=fmt)
        for s, gid, ox, oy in glyphs():
            if (s * upem > 100) != big:
                continue
            t = (s * k, 0, 0, -s * k, (ox - x0 + dx) * k, (oy - y0 + dy) * k)
            glyphset[order[gid]].draw(TransformPen(pen, t))
        return pen.getCommands()

    # Square: the type spans 83% of the side, centred — as in the supplied logo.
    side = tw / 0.833
    k = 1000 / side
    dx, dy = (side - tw) / 2, (side - th) / 2
    square = (
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1000 1000">\n'
        '  <title>You Matter Media</title>\n'
        f'  <rect width="1000" height="1000" fill="{CORAL}"/>\n'
        f'  <path fill="{CREAM}" d="{path(dx, dy, k, True)}"/>\n'
        f'  <path fill="{CREAM}" d="{path(dx, dy, k, False)}"/>\n'
        '</svg>\n'
    )
    pub = os.path.join(ROOT, 'public')
    for name in ('logo.svg', 'favicon.svg'):
        with open(os.path.join(pub, name), 'w', encoding='utf-8') as fh:
            fh.write(square)

    page = pymupdf.open(stream=square.encode(), filetype='svg')[0]
    for name, size in (('favicon-32.png', 32), ('apple-touch-icon.png', 180), ('logo-512.png', 512)):
        z = size / page.rect.width
        page.get_pixmap(matrix=pymupdf.Matrix(z, z), alpha=False).save(os.path.join(pub, name))

    # Horizontal lockup for the navbar and footer: the same type on a tighter
    # field, so MEDIA stays legible at navbar size.
    padx, pady = th * 0.22, th * 0.17
    k2 = 100 / (th + 2 * pady)
    width = fmt((tw + 2 * padx) * k2)
    js = f"""/**
 * The You Matter Media logo as vector outlines.
 *
 * Traced from the League Gothic glyphs embedded in the brand portfolio's
 * cover, at their exact positions and sizes, so the logo matches the
 * supplied artwork and never depends on the web font having loaded.
 * Generated by scripts/build_logo.py — do not edit by hand.
 *
 * Horizontal lockup: {width} × 100 units.
 */
export const LOGO = {{
  width: {width},
  height: 100,
  coral: '{CORAL}',
  cream: '{CREAM}',
  /** "YOU MATTER" */
  name: '{path(padx, pady, k2, True)}',
  /** "MEDIA" */
  media: '{path(padx, pady, k2, False)}',
}}
"""
    with open(os.path.join(ROOT, 'src', 'data', 'logo.js'), 'w', encoding='utf-8') as fh:
        fh.write(js)
    print(f'logo built: square 1000x1000, lockup {width}x100')


if __name__ == '__main__':
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    main(sys.argv[1])
